param(
    [string] $BuildOutput = '',
    [string] $Destination = (Join-Path $PSScriptRoot '../dist/bpp-modpack'),
    [string] $LauncherApk = (Join-Path $PSScriptRoot '../dist/app-release-aligned.apk'),
    [string] $InteropSnapshot = (Join-Path $PSScriptRoot '../android-managed'),
    [string] $SafeRuntime = (Join-Path $PSScriptRoot '../safe_Il2CppInterop.Runtime.dll'),
    [string] $SafeHarmony = (Join-Path $PSScriptRoot '../safe_Il2CppInterop.HarmonySupport.dll'),
    [switch] $Zip,
    # Package the BepInEx bridge with upstream's published Android Managed Payload bundled
    # (upstream-host/README.md) instead of this fork's plugin.
    [switch] $Upstream,
    [string] $OfficialPayloadCache = (Join-Path $PSScriptRoot '../dist/official-payload')
)

# Collects the BazaarPlusPlus Android build into a distributable BepInEx modpack.
# The plugins directory only carries plugin assemblies and application-level dependencies: BepInEx already
# ships the framework and the whole IL2CPP toolchain, and redistributing those copies
# causes assembly identity conflicts on the device.

$ErrorActionPreference = 'Stop'

if ([string]::IsNullOrWhiteSpace($BuildOutput)) {
    $BuildOutput = if ($Upstream) {
        Join-Path $PSScriptRoot 'upstream-host/BazaarPlusPlus.BepInExBridge/bin/Release/net10.0'
    } else {
        Join-Path $PSScriptRoot '../bazaarplusplus-mod/src/BazaarPlusPlus/bin/Debug/net6.0'
    }
}
if (-not (Test-Path $BuildOutput)) {
    throw "Build output not found: $BuildOutput (run the Android build first)."
}

$frameworkProvided = @(
    'BepInEx.Core', 'BepInEx.Unity.Common', 'BepInEx.Unity.IL2CPP',
    'Il2CppInterop.Common', 'Il2CppInterop.Generator', 'Il2CppInterop.HarmonySupport',
    'Il2CppInterop.Runtime', 'Cpp2IL.Core', 'LibCpp2IL', 'StableNameDotNet',
    'MonoMod.Backports', 'MonoMod.ILHelpers', 'MonoMod.RuntimeDetour', 'MonoMod.Utils',
    'Mono.Cecil', 'Mono.Cecil.Mdb', 'Mono.Cecil.Pdb', 'Mono.Cecil.Rocks',
    'AsmResolver', 'AsmResolver.DotNet', 'AsmResolver.PE', 'AsmResolver.PE.File',
    'AssetRipper.CIL', 'AssetRipper.Primitives', 'Iced', 'Disarm',
    'Gee.External.Capstone', 'WasmDisassembler', 'SemanticVersioning', '0Harmony'
)

# Game interop assemblies are generated by BepInEx on the device; shipping our copies would
# shadow them with a different generation, so everything mirrored from the interop snapshot is
# excluded by name.
$gameProvided = @()
if (-not (Test-Path -LiteralPath $InteropSnapshot)) {
    throw "Game interop snapshot missing: $InteropSnapshot. Refusing to package game assemblies."
}
if (Test-Path $InteropSnapshot) {
    $gameProvided = Get-ChildItem $InteropSnapshot -Filter *.dll |
        Where-Object { $_.BaseName -ne 'Newtonsoft.Json' } |
        ForEach-Object { $_.BaseName }
}

$plugins = Join-Path $Destination 'plugins'
if (-not (Test-Path -LiteralPath $safeRuntime)) {
    throw "Patched Android interop runtime not found: $safeRuntime"
}
$core = Join-Path $Destination 'core'
New-Item -ItemType Directory -Force -Path $core | Out-Null
# NextBep replaces the active core directory with the selected modpack's core.
# Start from the installed launcher's complete framework before applying the patches.
Add-Type -AssemblyName System.IO.Compression.FileSystem
$launcherArchive = [System.IO.Compression.ZipFile]::OpenRead($LauncherApk)
try {
    $frameworkEntry = $launcherArchive.GetEntry('assets/BepInEx.Android.zip')
    if ($null -eq $frameworkEntry) { throw "BepInEx framework missing from $LauncherApk" }
    $frameworkBuffer = New-Object System.IO.MemoryStream
    try {
        $frameworkInput = $frameworkEntry.Open()
        try { $frameworkInput.CopyTo($frameworkBuffer) } finally { $frameworkInput.Dispose() }
        $frameworkBuffer.Position = 0
        $frameworkArchive = New-Object System.IO.Compression.ZipArchive($frameworkBuffer, [System.IO.Compression.ZipArchiveMode]::Read)
        try {
            foreach ($entry in $frameworkArchive.Entries) {
                if (-not $entry.FullName.StartsWith('core/') -or $entry.FullName.EndsWith('/')) { continue }
                $coreFileName = $entry.FullName.Substring(5)
                if ($coreFileName.Contains('/') -or $coreFileName.Contains('\') -or $coreFileName -in @('.', '..')) {
                    throw "Unexpected framework core path: $($entry.FullName)"
                }
                [System.IO.Compression.ZipFileExtensions]::ExtractToFile($entry, (Join-Path $core $coreFileName), $true)
            }
        } finally { $frameworkArchive.Dispose() }
    } finally { $frameworkBuffer.Dispose() }
} finally { $launcherArchive.Dispose() }
if (-not (Test-Path -LiteralPath (Join-Path $core 'BepInEx.Unity.IL2CPP.dll'))) {
    throw 'Packaged core is missing the BepInEx entry assembly'
}
# Retire the old root-level runtime layout; the launcher applies core/ as a directory.
foreach ($retiredCore in @('Il2CppInterop.Runtime.dll', 'Il2CppInterop.HarmonySupport.dll')) {
    $retiredPath = Join-Path $Destination $retiredCore
    if (Test-Path -LiteralPath $retiredPath) { Remove-Item -LiteralPath $retiredPath -Force }
}
Copy-Item -LiteralPath $safeRuntime -Destination (Join-Path $core 'Il2CppInterop.Runtime.dll') -Force
if (-not (Test-Path -LiteralPath $safeHarmony)) { throw "Patched ARM64 Harmony support not found: $safeHarmony" }
Copy-Item -LiteralPath $safeHarmony -Destination (Join-Path $core 'Il2CppInterop.HarmonySupport.dll') -Force
if ($Upstream) {
    # Upstream's host binds MelonLoader-style interop names; make BepInEx generate them on the
    # device (tools/patch-bepinex-interop-prefix).
    $bepInExEntry = Join-Path $core 'BepInEx.Unity.IL2CPP.dll'
    & dotnet run --project (Join-Path $PSScriptRoot 'tools/patch-bepinex-interop-prefix/Patch.csproj') -- `
        $bepInExEntry $bepInExEntry $core
    if ($LASTEXITCODE -ne 0) { throw 'BepInEx interop prefix patch failed' }
}
New-Item -ItemType Directory -Force -Path $plugins | Out-Null
Get-ChildItem $plugins -Filter *.dll -ErrorAction SilentlyContinue | Remove-Item -Force

$copied = @()
Get-ChildItem $BuildOutput -Filter *.dll | ForEach-Object {
    if ($frameworkProvided -contains $_.BaseName) { return }
    if ($gameProvided -contains $_.BaseName) { return }
    Copy-Item $_.FullName (Join-Path $plugins $_.Name) -Force
    $copied += $_.Name
}

if (-not $Upstream) {
    # Keep portable DTO codecs separate from the game's same-name IL2CPP proxy assemblies. The
    # upstream payload needs no aliases: its interop names carry the Il2Cpp prefix.
    & dotnet run --project (Join-Path $PSScriptRoot 'tools/package-managed-codec/Package.csproj') -- $BuildOutput $plugins
    if ($LASTEXITCODE -ne 0) { throw 'Managed codec packaging failed' }
}
$sqliteNative = Join-Path $BuildOutput 'runtimes/android-arm64/native/libe_sqlite3.so'
if (-not (Test-Path -LiteralPath $sqliteNative)) { throw "Android SQLite library not found: $sqliteNative" }
Copy-Item -LiteralPath $sqliteNative -Destination (Join-Path $plugins 'libe_sqlite3.so') -Force
if ($Upstream) {
    # The payload the bridge installs on first start, pinned by upstream-host/official-payload.json;
    # the launcher fetches newer releases itself.
    $pin = Get-Content -Raw -LiteralPath (Join-Path $PSScriptRoot 'upstream-host/official-payload.json') | ConvertFrom-Json
    New-Item -ItemType Directory -Force -Path $OfficialPayloadCache | Out-Null
    $cached = Join-Path $OfficialPayloadCache "BazaarPlusPlus_$($pin.version)_android-aarch64-managed.zip"
    if (-not (Test-Path -LiteralPath $cached) -or (Get-FileHash -LiteralPath $cached).Hash.ToLower() -ne $pin.sha256) {
        Invoke-WebRequest -Uri $pin.url -OutFile $cached -UseBasicParsing
    }
    $actual = (Get-FileHash -LiteralPath $cached).Hash.ToLower()
    if ($actual -ne $pin.sha256 -or (Get-Item -LiteralPath $cached).Length -ne $pin.size) {
        Remove-Item -LiteralPath $cached -Force
        throw "Official payload $($pin.version) does not match its pin (sha256 $actual)"
    }
    Copy-Item -LiteralPath $cached -Destination (Join-Path $plugins 'BazaarPlusPlus.OfficialPayload.zip') -Force
}
$copied = @(Get-ChildItem -LiteralPath $plugins -Filter *.dll | ForEach-Object { $_.Name })

$epoch = [DateTimeOffset]'1970-01-01T00:00:00Z'
$createdAt = [long](([DateTimeOffset]::UtcNow - $epoch).TotalMilliseconds)
$manifest = '{"name":"bpp","packageName":"com.tempogames.thebazaar","createdAt":' +
    $createdAt + ',"modCount":' + $copied.Count + ',"createShortcut":false}'
[System.IO.File]::WriteAllText(
    (Join-Path $Destination 'modpack.json'),
    $manifest,
    (New-Object System.Text.UTF8Encoding($false))
)

if ($Zip) {
    $zipPath = "$Destination.zip"
    if (Test-Path $zipPath) { Remove-Item $zipPath -Force }
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    [System.IO.Compression.ZipFile]::CreateFromDirectory($Destination, $zipPath)
    Write-Host "Archive: $zipPath"
}

Write-Host "modpack ready: $Destination"
Write-Host ("shipping {0} assemblies" -f $copied.Count)
$copied | Sort-Object | ForEach-Object { Write-Host ("  " + $_) }
